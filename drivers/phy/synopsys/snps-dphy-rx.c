const struct snps_dphy_freq_range *dphy_configuration(struct phy *phy, u64 mbps)
{
	struct snps_dphy *dphy = phy_get_drvdata(phy);
	int i;

	for (i = 0; i < ARRAY_SIZE(frequency_range) &&
	     (frequency_range[i].bitrate < mbps); i++)
		;

	if (i == ARRAY_SIZE(frequency_range)) {
		dev_err(dphy->dev, "unsupported frequency requested\n");
		return NULL;
	}

	return &frequency_range[i];
}
